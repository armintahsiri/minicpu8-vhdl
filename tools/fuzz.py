def vhdl_rom(name, words):
    lines = [f"  constant {name} : rom_t := ("]
    if len(words) == 1:
        lines.append(f'    0 => x"{words[0]:04X}");')
        return lines
    for i in range(0, len(words), 4):
        chunk = ", ".join(f'x"{w:04X}"' for w in words[i:i + 4])
        tail = "," if i + 4 < len(words) else ""
        lines.append(f"    {chunk}{tail}")
    lines.append("  );")
    return lines


def vhdl_ram(name, ram):
    lines = [f"  constant {name} : ram_init_t := ("]
    if not ram:
        ram = [0]
    for i in range(0, len(ram), 8):
        chunk = ", ".join(f'{j} => x"{ram[j]:02X}"'
                          for j in range(i, min(i + 8, len(ram))))
        tail = "," if i + 8 < len(ram) else ""
        lines.append(f"    {chunk}{tail}")
    lines.append("  );")
    return lines


def make_data_vhdl(programs, images):
    lines = [
        "-- GENERATED by tools/fuzz.py -- DO NOT EDIT",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use work.minicpu_pkg.all;",
        "",
        "package fuzz_data is",
    ]
    for p in programs:
        words, ram = images[p.index]
        lines += vhdl_rom(f"P{p.index}", words)
        lines += vhdl_ram(f"M{p.index}", ram)
    lines += ["end package fuzz_data;", ""]
    return "\n".join(lines)


