#!/usr/bin/env python3
"""Differential test: random programs, golden model vs VHDL CPU.

For each generated program:
  1. assemble it,
  2. run it in tools/isa_sim.py (the golden model),
  3. run the same ROM/RAM image in the VHDL CPU through a generated testbench,
  4. compare final PC, flags, registers, cycles and all 256 RAM bytes.

A mismatch prints the assembly and both final states and exits non-zero.
Artifacts are left in --dir for inspection.

Usage:
  python3 tools/fuzz.py --count 20 --seed 20251019 --dir build/fuzz_quick
  python3 tools/fuzz.py --count 200 --seed 20251019 --dir build/fuzz
"""
