def trace_coverage(cpu):
    """Decode the executed trace into instruction-category counts."""
    cov = Counter()
    for _, w in cpu.trace:
        op = (w >> 12) & 0xF
        func = w & 0x7
        cond = (w >> 8) & 0xF
        if op <= 0x7:
            cov[f"ALU_{op}"] += 1
        elif op == 0x8:
            cov["LOAD"] += 1
        elif op == 0x9:
            cov["LOADI"] += 1
        elif op == 0xA:
            cov["BEQ"] += 1
        elif op == 0xB:
            cov["BNE"] += 1
        elif op == 0xC:
            if cond == 0xF:
                cov["CALL"] += 1
            elif cond <= 0x8:
                cov[f"COND_{cond}"] += 1
            else:
                cov["RESERVED_COND"] += 1
        elif op == 0xD:
            cov["STORE"] += 1
        elif op == 0xE:
            cov["ADDI"] += 1
        elif op == 0xF:
            if func == 0x0:
                cov["NOP"] += 1
            elif func == 0x2:
                cov["RET"] += 1
            elif func == 0x3:
                cov["CMP"] += 1
    cov["HALT"] += 1          # HALT is detected, not executed, so not traced
    return cov


def required_coverage():
    return ({f"ALU_{i}" for i in range(8)} |
            {"LOAD", "LOADI", "BEQ", "BNE", "STORE", "ADDI", "CMP", "RET",
             "CALL", "HALT", "NOP"} |
            {f"COND_{i}" for i in range(9)})


def expected_state(cpu, io_mode=False):
    s = cpu.state()
    f = s["flags"]
    flags_nibble = (f["z"] << 3) | (f["n"] << 2) | (f["c"] << 1) | f["v"]
    out = {
        "pc": s["pc"],
        "flags": flags_nibble,
        "regs": "".join(f"{b:02X}" for b in s["regs"]),
        "ram": "".join(f"{b:02X}" for b in s["ram"]),
        "cycles": s["cycles"],
    }
    if io_mode:
        out["uart"] = s["uart_hex"]
        out["uart_errors"] = 0
        out["gpio_out"] = s["gpio_out"]
    return out


def parse_output(text, io_mode=False):
    states, rams = {}, {}
    for line in text.splitlines():
        m = re.search(r"FUZZ_STATE\s+(\d+)\s+PC=([0-9A-Fa-f]+)\s+"
                      r"FLAGS=([0-9A-Fa-f]+)\s+REGS=([0-9A-Fa-f]+)\s+"
                      r"CYCLES=(\d+)", line)
        if m:
            i = int(m.group(1))
            states[i] = {
                "pc": int(m.group(2), 16),
                "flags": int(m.group(3), 16),
                "regs": m.group(4).upper(),
                "cycles": int(m.group(5)),
            }
            continue
        m = re.search(r"FUZZ_RAM\s+(\d+)\s+([01])\s+([0-9A-Fa-f]+)", line)
        if m:
            i = int(m.group(1))
            half = int(m.group(2))
            rams.setdefault(i, {})[half] = m.group(3).upper()
            continue
        if io_mode:
            m = re.search(r"FUZZ_UART\s+(\d+)\s+COUNT=(\d+)\s+"
                          r"ERRORS=(\d+)\s+DATA=([0-9A-Fa-f]+)", line)
            if m:
                i = int(m.group(1))
                n = int(m.group(2))
                packed = int(m.group(4), 16)
                raw = [(packed >> (8 * j)) & 0xFF for j in range(n)]
                states.setdefault(i, {})["uart"] = "".join(
                    f"{b:02X}" for b in raw)
                states[i]["uart_errors"] = int(m.group(3))
                continue
            m = re.search(r"FUZZ_GPIO\s+(\d+)\s+VALUE=([0-9A-Fa-f]+)", line)
            if m:
                i = int(m.group(1))
                states.setdefault(i, {})["gpio_out"] = int(m.group(2), 16)
                continue
    for i, halves in rams.items():
        if 0 in halves and 1 in halves and i in states:
            states[i]["ram"] = halves[0] + halves[1]
    return states


def state_diff(exp, got):
    diffs = []
    keys = ["pc", "flags", "regs", "ram", "cycles"]
    keys += [k for k in ("uart", "uart_errors", "gpio_out") if k in exp]
    for key in keys:
        if key not in got:
            diffs.append(f"{key}: missing from VHDL dump")
        elif exp[key] != got[key]:
            if key == "ram":
                bad = [j for j in range(256)
                       if exp["ram"][2*j:2*j+2] != got["ram"][2*j:2*j+2]]
                diffs.append(f"ram: {len(bad)} bytes differ, first at "
                             f"{bad[0]:02X} (exp {exp['ram'][2*bad[0]:2*bad[0]+2]}, "
                             f"got {got['ram'][2*bad[0]:2*bad[0]+2]})")
            else:
                diffs.append(f"{key}: expected {exp[key]!r}, got {got[key]!r}")
    return diffs


def run_nvc(nvc, outdir, log_path):
    core = [str(ROOT / s) for s in CORE_SOURCES]
    gen = [str(outdir / "fuzz_data.vhd"), str(outdir / "fuzz_tb.vhd")]
    cmd_init = [nvc, "--std=08", "--work=work", "--init"]
    subprocess.run(cmd_init, cwd=outdir, check=True,
                   stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    support = [str(ROOT / s) for s in SUPPORT_SOURCES]
    cmd_a = [nvc, "--std=08", "--work=work", "-a"] + core + support + gen
    r = subprocess.run(cmd_a, cwd=outdir, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, text=True)
    log = r.stdout
    if r.returncode != 0:
        log_path.write_text(log)
        print(log[-4000:])
        raise SystemExit("fuzz: VHDL analysis failed (see %s)" % log_path)
    r = subprocess.run([nvc, "--std=08", "--work=work", "-e", "fuzz_tb", "-r"],
                       cwd=outdir, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, text=True)
    log += r.stdout
    log_path.write_text(log)
    if r.returncode != 0 or "** Failure:" in log or "** Error:" in log:
        print(log[-6000:])
        raise SystemExit("fuzz: VHDL simulation failed (see %s)" % log_path)
    return log


def run_ghdl(ghdl, outdir, log_path):
    core = [str(ROOT / s) for s in CORE_SOURCES]
    support = [str(ROOT / s) for s in SUPPORT_SOURCES]
    gen = [str(outdir / "fuzz_data.vhd"), str(outdir / "fuzz_tb.vhd")]
    work = outdir / "ghdl-work"
    work.mkdir(exist_ok=True)
    cmd = [ghdl, "-a", "--std=08", f"--workdir={work}"] + core + support + gen
    r = subprocess.run(cmd, cwd=outdir, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, text=True)
    log = r.stdout
    if r.returncode == 0:
        r = subprocess.run([ghdl, "--elab-run", "--std=08", f"--workdir={work}",
                            "fuzz_tb", "--assert-level=error"], cwd=outdir,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                           text=True)
        log += r.stdout
    log_path.write_text(log)
    if r.returncode != 0 or "FUZZ_TIMEOUT" in log or "GLOBAL WATCHDOG TIMEOUT" in log:
        print(log[-6000:])
        raise SystemExit("fuzz: GHDL analysis/simulation failed (see %s)" % log_path)
    return log


def main():
    ap = argparse.ArgumentParser(description="MiniCPU-8 differential fuzzer")
    ap.add_argument("--count", type=int, default=20)
    ap.add_argument("--seed", type=int, default=20251019)
    ap.add_argument("--dir", default="build/fuzz_quick")
    ap.add_argument("--nvc", default=os.environ.get("NVC", "nvc"))
    ap.add_argument("--io", action="store_true",
                    help="I/O-fuzz mode: UART/GPIO/cycle-counter programs")
    ap.add_argument("--gpio-schedule",
                    help="shared cycle/value GPIO schedule file (defaults to static pin value)")
    ap.add_argument("--random-gpio-schedule", action="store_true",
                    help="generate a reproducible random GPIO schedule from --seed")
    ap.add_argument("--gpio-boundary", action="store_true",
                    help="run the directed LOAD-at-c=4/6/8 GPIO schedule boundary program")
    ap.add_argument("--gpio-transition-cycle", type=int,
                    help="boundary schedule transition cycle (3, 4, or 5)")
    ap.add_argument("--ghdl", help="also run generated testbench with this GHDL executable")
    args = ap.parse_args()

    if args.count < 1:
        raise SystemExit("fuzz: --count must be positive")
    outdir = Path(args.dir).resolve()
    if ROOT != outdir and ROOT not in outdir.parents:
        raise SystemExit(f"fuzz: refusing to use a directory outside the workspace: {outdir}")
    if outdir.exists():
        shutil.rmtree(outdir)
    outdir.mkdir(parents=True)
    (outdir / "programs").mkdir()

    if args.io:
        programs = random_programs.generate_io_programs(args.count, args.seed)
        if args.gpio_boundary:
            if args.gpio_transition_cycle not in (3, 4, 5):
                raise SystemExit("fuzz: --gpio-boundary requires transition cycle 3, 4, or 5")
            boundary_asm = """\
                loadi r1, GPIO_IN
                nop
                nop
                nop
                load r2, [r1+0]
                nop
                load r3, [r1+0]
                nop
                load r4, [r1+0]
                halt
            """
            programs = [random_programs.GeneratedProgram(
                index=0, name="gpio_boundary", asm=boundary_asm,
                gpio_in=0x11, mode="io")]
        if args.gpio_schedule and args.random_gpio_schedule:
            raise SystemExit("fuzz: choose a file schedule or --random-gpio-schedule")
        if args.gpio_boundary and (args.gpio_schedule or args.random_gpio_schedule):
            raise SystemExit("fuzz: boundary mode creates its own schedule")
        if args.gpio_boundary:
            gpio_schedule = [(0, 0x11), (args.gpio_transition_cycle, 0x55)]
            schedule_path = outdir / "gpio-schedule.txt"
            schedule_path.write_text("# directed boundary cycle value schedule\n" +
                                     "".join(f"{c} 0x{v:02X}\n" for c, v in gpio_schedule))
            gpio_schedule = isa_sim.read_gpio_schedule(schedule_path)
        elif args.random_gpio_schedule:
            rng = random.Random(args.seed ^ 0x4750494F)
            gpio_schedule = [(0, 0)]
            for cycle in sorted(rng.sample(range(4, 250), 12)):
                gpio_schedule.append((cycle, rng.randrange(256)))
            schedule_path = outdir / "gpio-schedule.txt"
            schedule_path.write_text("# generated cycle value schedule\n" +
                                     "".join(f"{c} 0x{v:02X}\n" for c, v in gpio_schedule))
            gpio_schedule = isa_sim.read_gpio_schedule(schedule_path)
        else:
            gpio_schedule = (isa_sim.read_gpio_schedule(args.gpio_schedule)
                             if args.gpio_schedule else None)
    else:
        programs = random_programs.generate_programs(args.count, args.seed)
        gpio_schedule = None
    images, expected = {}, {}
    coverage = Counter()
    for p in programs:
        res = assembler.assemble_with_data(p.asm)
        images[p.index] = (res.words, res.ram)
        cpu = isa_sim.MiniCPU8(
            res.words, res.ram, max_cycles=5000,
            gpio_in=p.gpio_in, clks_per_bit=(UART_CPB if args.io else 217),
            gpio_schedule=(gpio_schedule or [(0, p.gpio_in)])
        ).run()
        if not cpu.halted or cpu.timeout:
            print(p.asm)
            raise SystemExit(f"fuzz: generated program {p.name} did not halt "
                             f"({cpu.compact()})")
        expected[p.index] = expected_state(cpu, io_mode=args.io)
        if args.gpio_boundary:
            manual = {
                3: [0x11, 0x55, 0x55],
                4: [0x11, 0x55, 0x55],
                5: [0x11, 0x11, 0x55],
            }[args.gpio_transition_cycle]
            if cpu.regs[2:5] != manual:
                raise SystemExit(f"fuzz: hand-derived GPIO boundary expectation failed: "
                                 f"expected {manual}, got {cpu.regs[2:5]}")
        coverage.update(trace_coverage(cpu))
        (outdir / "programs" / (p.name + ".asm")).write_text(p.asm)

    (outdir / "fuzz_data.vhd").write_text(make_data_vhdl(programs, images))
    (outdir / "fuzz_tb.vhd").write_text(
        make_tb_vhdl(len(programs), programs, io_mode=args.io,
                     gpio_schedule=gpio_schedule))
    (outdir / "expected.json").write_text(json.dumps(expected, indent=1))

    log = run_nvc(args.nvc, outdir, outdir / "nvc.log")
    got = parse_output(log, io_mode=args.io)
    if args.ghdl:
        ghdl_log = run_ghdl(args.ghdl, outdir, outdir / "ghdl.log")
        ghdl_got = parse_output(ghdl_log, io_mode=args.io)
        for p in programs:
            diffs = state_diff(expected[p.index], ghdl_got.get(p.index, {}))
            if diffs:
                print(p.asm)
                for diff in diffs:
                    print("GHDL DIFF", diff)
                raise SystemExit(f"fuzz: GHDL mismatch in {p.name}")

    mismatches = []
    for p in programs:
        i = p.index
        if i not in got:
            mismatches.append((p, expected[i], None, ["no FUZZ_STATE line found"]))
            continue
        diffs = state_diff(expected[i], got[i])
        if diffs:
            mismatches.append((p, expected[i], got[i], diffs))

    if mismatches:
        print("=" * 70)
        print(f"FUZZ: {len(mismatches)} of {len(programs)} programs MISMATCHED")
        print("=" * 70)
        for p, exp, act, diffs in mismatches[:10]:
            print(f"\n--- {p.name} (artifacts in {outdir}) ---")
            print(p.asm)
            print("expected:", json.dumps(exp))
            print("actual:  ", json.dumps(act))
            for d in diffs:
                print("  DIFF", d)
        if len(mismatches) > 10:
            print(f"... {len(mismatches)-10} more mismatches")
        raise SystemExit(1)

    missing = sorted(required_coverage() - set(coverage))
    cov_line = " ".join(f"{k}={coverage[k]}" for k in sorted(required_coverage()))
    total = sum(expected[p.index]["cycles"] for p in programs)
    mode = "I/O" if args.io else "ALU/RAM"
    print(f"FUZZ ({mode}): {len(programs)} programs, 0 NVC"
          f"{'/GHDL' if args.ghdl else ''} mismatches "
          f"(seed {args.seed}, {total} total instructions, "
          f"max {max(e['cycles'] for e in expected.values())} cycles)")
    print("FUZZ coverage: " + cov_line)
    if args.io:
        for p in programs:
            e = expected[p.index]
            uart = e["uart"] if e["uart"] else "(none)"
            print(f"  {p.name}: uart={uart} gpio_out=0x{e['gpio_out']:02X} "
                  f"cycles={e['cycles']}")
        if any(got[p.index].get("uart_errors", 0) != 0 for p in programs):
            raise SystemExit("fuzz: UART framing errors in I/O mode")
    elif missing:
        print("FUZZ coverage missing: " + ", ".join(missing))
        if args.count >= 20:
            raise SystemExit("fuzz: required instruction coverage not reached")
        print("FUZZ: (small run: coverage gaps are reported but not fatal)")


if __name__ == "__main__":
    main()
