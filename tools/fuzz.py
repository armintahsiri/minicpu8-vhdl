#!/usr/bin/env python3
"""Differential test: random programs, golden model vs VHDL CPU.

For each generated program:
  1. assemble it,
  2. run it in tools/isa_sim.py (the golden model),
  3. run the same ROM/RAM image in the VHDL CPU through a generated testbench,
  4. compare final PC, flags, registers, cycles and all 256 RAM bytes.

A mismatch prints the assembly and both final states and exits non-zero.
Artifacts are left in --dir for inspection.

Usage:
  python3 tools/fuzz.py --count 20 --seed 20251019 --dir build/fuzz_quick
  python3 tools/fuzz.py --count 200 --seed 20251019 --dir build/fuzz
"""
import argparse
import json
import os
import re
import shutil
import subprocess
from collections import Counter
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))
import assembler  # noqa: E402
import isa_sim    # noqa: E402
import random_programs  # noqa: E402

CORE_SOURCES = [
    "minicpu_pkg.vhd", "alu.vhd", "register_file.vhd", "flag_reg.vhd",
    "pc.vhd", "instr_rom.vhd", "data_ram.vhd", "branch_cond.vhd",
    "control_unit.vhd", "cpu_top.vhd",
]

MAX_CYCLES = 1000


def vhdl_rom(name, words):
    lines = [f"  constant {name} : rom_t := ("]
    if len(words) == 1:
        lines.append(f'    0 => x"{words[0]:04X}");')
        return lines
    for i in range(0, len(words), 4):
        chunk = ", ".join(f'x"{w:04X}"' for w in words[i:i + 4])
        tail = "," if i + 4 < len(words) else ""
        lines.append(f"    {chunk}{tail}")
    lines.append("  );")
    return lines


def vhdl_ram(name, ram):
    lines = [f"  constant {name} : ram_init_t := ("]
    if not ram:
        ram = [0]
    for i in range(0, len(ram), 8):
        chunk = ", ".join(f'{j} => x"{ram[j]:02X}"'
                          for j in range(i, min(i + 8, len(ram))))
        tail = "," if i + 8 < len(ram) else ""
        lines.append(f"    {chunk}{tail}")
    lines.append("  );")
    return lines


def make_data_vhdl(programs, images):
    lines = [
        "-- GENERATED by tools/fuzz.py -- DO NOT EDIT",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use work.minicpu_pkg.all;",
        "",
        "package fuzz_data is",
    ]
    for p in programs:
        words, ram = images[p.index]
        lines += vhdl_rom(f"P{p.index}", words)
        lines += vhdl_ram(f"M{p.index}", ram)
    lines += ["end package fuzz_data;", ""]
    return "\n".join(lines)


def make_tb_vhdl(count):
    last = count - 1
    lines = [
        "-- GENERATED by tools/fuzz.py -- DO NOT EDIT",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use ieee.numeric_std.all;",
        "use std.env.all;",
        "use work.minicpu_pkg.all;",
        "",
        "entity fuzz_tb is",
        "end entity fuzz_tb;",
        "",
        "architecture sim of fuzz_tb is",
        "  type halted_vec_t is array (natural range <>) of std_logic;",
        "  type pc_vec_t     is array (natural range <>) of byte_t;",
        "  type flags_vec_t  is array (natural range <>) of std_logic_vector(3 downto 0);",
        "  type regs_vec_t   is array (natural range <>) of regfile_t;",
        "  type ram_vec_t    is array (natural range <>) of ram_t;",
        "  type cycle_vec_t  is array (natural range <>) of natural;",
        "  type bool_vec_t   is array (natural range <>) of boolean;",
        "",
        "  constant FUZZ_COUNT : natural := %d;" % count,
        "  constant MAX_CYCLES : natural := %d;" % MAX_CYCLES,
        "  signal clk : std_logic := '0';",
        "  signal rst : std_logic := '1';",
        "  signal halted_v : halted_vec_t(0 to %d);" % last,
        "  signal pc_v     : pc_vec_t(0 to %d);" % last,
        "  signal flags_v  : flags_vec_t(0 to %d);" % last,
        "  signal regs_v   : regs_vec_t(0 to %d);" % last,
        "  signal ram_v    : ram_vec_t(0 to %d);" % last,
        "",
        "  function regs_hex (r : regfile_t) return string is",
        "    variable s : string(1 to 16);",
        "  begin",
        "    for j in 0 to 7 loop",
        "      s(2*j+1 to 2*j+2) := to_hstring(r(j));",
        "    end loop;",
        "    return s;",
        "  end function;",
        "",
        "  function ram_half_hex (r : ram_t; half : natural) return string is",
        "    variable s : string(1 to 256);",
        "  begin",
        "    for j in 0 to 127 loop",
        "      s(2*j+1 to 2*j+2) := to_hstring(r(half*128 + j));",
        "    end loop;",
        "    return s;",
        "  end function;",
        "",
        "begin",
        "  clk <= not clk after 5 ns;",
        "",
    ]
    for i in range(count):
        lines += [
            f"  dut{i} : entity work.cpu_top",
            f"    generic map (PROGRAM => work.fuzz_data.P{i},",
            f"                 RAM_INIT => work.fuzz_data.M{i})",
            f"    port map (clk => clk, rst => rst, halted => halted_v({i}),",
            f"              dbg_pc => pc_v({i}), dbg_flags => flags_v({i}),",
            f"              dbg_regs => regs_v({i}), dbg_ram => ram_v({i}));",
            "",
        ]
    lines += [
        "  stim : process",
        "    variable cycles : cycle_vec_t(0 to %d) := (others => 0);" % last,
        "    variable active : bool_vec_t(0 to %d) := (others => true);" % last,
        "    variable all_halted : boolean;",
        "  begin",
        "    rst <= '1';",
        "    wait until rising_edge(clk);",
        "    wait until rising_edge(clk);",
        "    wait until falling_edge(clk);",
        "    rst <= '0';",
        "",
        "    loop",
        "      all_halted := true;",
        "      for i in 0 to FUZZ_COUNT-1 loop",
        "        active(i) := halted_v(i) /= '1';",
        "        if active(i) then",
        "          all_halted := false;",
        "        end if;",
        "      end loop;",
        "      exit when all_halted;",
        "",
        "      wait until rising_edge(clk);",
        "      for i in 0 to FUZZ_COUNT-1 loop",
        "        if active(i) then",
        "          cycles(i) := cycles(i) + 1;",
        "          if cycles(i) > MAX_CYCLES then",
        '            report "FUZZ_TIMEOUT program " & integer\'image(i)',
        "              severity failure;",
        "          end if;",
        "        end if;",
        "      end loop;",
        "      wait for 1 ns;",
        "    end loop;",
        "    wait for 1 ns;",
        "",
        "    for i in 0 to FUZZ_COUNT-1 loop",
        '      report "FUZZ_STATE " & integer\'image(i) &',
        '             " PC=" & to_hstring(pc_v(i)) &',
        '             " FLAGS=" & to_hstring(flags_v(i)) &',
        '             " REGS=" & regs_hex(regs_v(i)) &',
        '             " CYCLES=" & integer\'image(cycles(i))',
        "        severity note;",
        '      report "FUZZ_RAM " & integer\'image(i) & " 0 " &',
        "             ram_half_hex(ram_v(i), 0) severity note;",
        '      report "FUZZ_RAM " & integer\'image(i) & " 1 " &',
        "             ram_half_hex(ram_v(i), 1) severity note;",
        "    end loop;",
        '    report "FUZZ_TB: ALL STATES DUMPED" severity note;',
        "    finish;",
        "  end process;",
        "",
        "  watchdog : process",
        "  begin",
        "    wait for 5 ms;",
        '    report "FUZZ_TB: GLOBAL WATCHDOG TIMEOUT" severity failure;',
        "    wait;",
        "  end process;",
        "",
        "end architecture sim;",
        "",
    ]
    return "\n".join(lines)


def trace_coverage(cpu):
    """Decode the executed trace into instruction-category counts."""
    cov = Counter()
    for _, w in cpu.trace:
        op = (w >> 12) & 0xF
        func = w & 0x7
        cond = (w >> 8) & 0xF
        if op <= 0x7:
            cov[f"ALU_{op}"] += 1
        elif op == 0x8:
            cov["LOAD"] += 1
        elif op == 0x9:
            cov["LOADI"] += 1
        elif op == 0xA:
            cov["BEQ"] += 1
        elif op == 0xB:
            cov["BNE"] += 1
        elif op == 0xC:
            if cond == 0xF:
                cov["CALL"] += 1
            elif cond <= 0x8:
                cov[f"COND_{cond}"] += 1
            else:
                cov["RESERVED_COND"] += 1
        elif op == 0xD:
            cov["STORE"] += 1
        elif op == 0xE:
            cov["ADDI"] += 1
        elif op == 0xF:
            if func == 0x0:
                cov["NOP"] += 1
            elif func == 0x2:
                cov["RET"] += 1
            elif func == 0x3:
                cov["CMP"] += 1
    cov["HALT"] += 1          # HALT is detected, not executed, so not traced
    return cov


def required_coverage():
    return ({f"ALU_{i}" for i in range(8)} |
            {"LOAD", "LOADI", "BEQ", "BNE", "STORE", "ADDI", "CMP", "RET",
             "CALL", "HALT", "NOP"} |
            {f"COND_{i}" for i in range(9)})


def expected_state(cpu):
    s = cpu.state()
    f = s["flags"]
    flags_nibble = (f["z"] << 3) | (f["n"] << 2) | (f["c"] << 1) | f["v"]
    return {
        "pc": s["pc"],
        "flags": flags_nibble,
        "regs": "".join(f"{b:02X}" for b in s["regs"]),
        "ram": "".join(f"{b:02X}" for b in s["ram"]),
        "cycles": s["cycles"],
    }


def parse_output(text):
    states, rams = {}, {}
    for line in text.splitlines():
        m = re.search(r"FUZZ_STATE\s+(\d+)\s+PC=([0-9A-Fa-f]+)\s+"
                      r"FLAGS=([0-9A-Fa-f]+)\s+REGS=([0-9A-Fa-f]+)\s+"
                      r"CYCLES=(\d+)", line)
        if m:
            i = int(m.group(1))
            states[i] = {
                "pc": int(m.group(2), 16),
                "flags": int(m.group(3), 16),
                "regs": m.group(4).upper(),
                "cycles": int(m.group(5)),
            }
            continue
        m = re.search(r"FUZZ_RAM\s+(\d+)\s+([01])\s+([0-9A-Fa-f]+)", line)
        if m:
            i = int(m.group(1))
            half = int(m.group(2))
            rams.setdefault(i, {})[half] = m.group(3).upper()
    for i, halves in rams.items():
        if 0 in halves and 1 in halves and i in states:
            states[i]["ram"] = halves[0] + halves[1]
    return states


def state_diff(exp, got):
    diffs = []
    for key in ("pc", "flags", "regs", "ram", "cycles"):
        if key not in got:
            diffs.append(f"{key}: missing from VHDL dump")
        elif exp[key] != got[key]:
            if key == "ram":
                bad = [j for j in range(256)
                       if exp["ram"][2*j:2*j+2] != got["ram"][2*j:2*j+2]]
                diffs.append(f"ram: {len(bad)} bytes differ, first at "
                             f"{bad[0]:02X} (exp {exp['ram'][2*bad[0]:2*bad[0]+2]}, "
                             f"got {got['ram'][2*bad[0]:2*bad[0]+2]})")
            else:
                diffs.append(f"{key}: expected {exp[key]!r}, got {got[key]!r}")
    return diffs


def run_nvc(nvc, outdir, log_path):
    core = [str(ROOT / s) for s in CORE_SOURCES]
    gen = [str(outdir / "fuzz_data.vhd"), str(outdir / "fuzz_tb.vhd")]
    cmd_init = [nvc, "--std=08", "--work=work", "--init"]
    subprocess.run(cmd_init, cwd=outdir, check=True,
                   stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    cmd_a = [nvc, "--std=08", "--work=work", "-a"] + core + gen
    r = subprocess.run(cmd_a, cwd=outdir, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, text=True)
    log = r.stdout
    if r.returncode != 0:
        log_path.write_text(log)
        print(log[-4000:])
        raise SystemExit("fuzz: VHDL analysis failed (see %s)" % log_path)
    r = subprocess.run([nvc, "--std=08", "--work=work", "-e", "fuzz_tb", "-r"],
                       cwd=outdir, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, text=True)
    log += r.stdout
    log_path.write_text(log)
    if r.returncode != 0 or "** Failure:" in log or "** Error:" in log:
        print(log[-6000:])
        raise SystemExit("fuzz: VHDL simulation failed (see %s)" % log_path)
    return log


def main():
    ap = argparse.ArgumentParser(description="MiniCPU-8 differential fuzzer")
    ap.add_argument("--count", type=int, default=20)
    ap.add_argument("--seed", type=int, default=20251019)
    ap.add_argument("--dir", default="build/fuzz_quick")
    ap.add_argument("--nvc", default=os.environ.get("NVC", "nvc"))
    args = ap.parse_args()

    if args.count < 1:
        raise SystemExit("fuzz: --count must be positive")
    outdir = Path(args.dir).resolve()
    if ROOT != outdir and ROOT not in outdir.parents:
        raise SystemExit(f"fuzz: refusing to use a directory outside the workspace: {outdir}")
    if outdir.exists():
        shutil.rmtree(outdir)
    outdir.mkdir(parents=True)
    (outdir / "programs").mkdir()

    programs = random_programs.generate_programs(args.count, args.seed)
    images, expected = {}, {}
    coverage = Counter()
    for p in programs:
        res = assembler.assemble_with_data(p.asm)
        images[p.index] = (res.words, res.ram)
        cpu = isa_sim.MiniCPU8(res.words, res.ram, max_cycles=5000).run()
        if not cpu.halted or cpu.timeout:
            print(p.asm)
            raise SystemExit(f"fuzz: generated program {p.name} did not halt "
                             f"({cpu.compact()})")
        expected[p.index] = expected_state(cpu)
        coverage.update(trace_coverage(cpu))
        (outdir / "programs" / (p.name + ".asm")).write_text(p.asm)

    (outdir / "fuzz_data.vhd").write_text(make_data_vhdl(programs, images))
    (outdir / "fuzz_tb.vhd").write_text(make_tb_vhdl(len(programs)))
    (outdir / "expected.json").write_text(json.dumps(expected, indent=1))

    log = run_nvc(args.nvc, outdir, outdir / "nvc.log")
    got = parse_output(log)

    mismatches = []
    for p in programs:
        i = p.index
        if i not in got:
            mismatches.append((p, expected[i], None, ["no FUZZ_STATE line found"]))
            continue
        diffs = state_diff(expected[i], got[i])
        if diffs:
            mismatches.append((p, expected[i], got[i], diffs))

    if mismatches:
        print("=" * 70)
        print(f"FUZZ: {len(mismatches)} of {len(programs)} programs MISMATCHED")
        print("=" * 70)
        for p, exp, act, diffs in mismatches[:10]:
            print(f"\n--- {p.name} (artifacts in {outdir}) ---")
            print(p.asm)
            print("expected:", json.dumps(exp))
            print("actual:  ", json.dumps(act))
            for d in diffs:
                print("  DIFF", d)
        if len(mismatches) > 10:
            print(f"... {len(mismatches)-10} more mismatches")
        raise SystemExit(1)

    missing = sorted(required_coverage() - set(coverage))
    cov_line = " ".join(f"{k}={coverage[k]}" for k in sorted(required_coverage()))
    total = sum(expected[p.index]["cycles"] for p in programs)
    print(f"FUZZ: {len(programs)} programs, 0 mismatches "
          f"(seed {args.seed}, {total} total instructions, "
          f"max {max(e['cycles'] for e in expected.values())} cycles)")
    print("FUZZ coverage: " + cov_line)
    if missing:
        print("FUZZ coverage missing: " + ", ".join(missing))
        if args.count >= 20:
            raise SystemExit("fuzz: required instruction coverage not reached")
        print("FUZZ: (small run: coverage gaps are reported but not fatal)")


if __name__ == "__main__":
    main()
