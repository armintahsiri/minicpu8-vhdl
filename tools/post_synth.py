#!/usr/bin/env python3
"""Post-synthesis verification for MiniCPU-8 (Phase 3).

For each selected program this script:
  1. synthesizes post_synth_top with GHDL + Yosys (iCE40 mapping),
  2. writes the actual gate-level Verilog netlist (write_verilog),
  3. compiles it with Icarus Verilog and Yosys' iCE40 cells_sim.v,
  4. runs a small Verilog testbench that captures UART and dumps final state,
  5. compares PC, flags, registers, all 256 RAM bytes, cycles and UART bytes
     with tools/isa_sim.py (the golden model).

Usage (from the repository root):
  GHDL_PLUGIN=/path/to/ghdl.so GHDL_PREFIX=/path/to/ghdl/lib/ghdl \
      python3 tools/post_synth.py
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))
import assembler  # noqa: E402
import isa_sim    # noqa: E402

SOURCES = [
    "minicpu_pkg.vhd", "alu.vhd", "register_file.vhd", "flag_reg.vhd",
    "pc.vhd", "instr_rom.vhd", "data_ram.vhd", "branch_cond.vhd",
    "control_unit.vhd", "uart_tx.vhd", "gpio.vhd", "cycle_counter.vhd",
    "mmio.vhd", "cpu_top.vhd", "post_synth_top.vhd",
]
CLKS_PER_BIT = 10
MAX_CYCLES = 10000

TB_TEMPLATE = r"""// GENERATED by tools/post_synth.py -- post-synthesis testbench
`timescale 1ns/1ps
module post_tb;
  reg clk = 0;
  reg rst = 1;
  reg [7:0] gpio_in = 0;
  wire halted;
  wire [7:0] gpio_out;
  wire uart_tx;
  wire [7:0] dbg_pc;
  wire [3:0] dbg_flags;
  wire [63:0] dbg_regs;
  wire [2047:0] dbg_ram;

  localparam integer CLK_PERIOD = 10;
  localparam integer BIT_TIME = CLK_PERIOD * __CPB__;
  localparam integer MAX_CYCLES = __MAX_CYCLES__;

  integer cycles;
  integer i;
  integer rx_count;
  integer rx_errors;
  integer rxi;
  reg [7:0] rx_byte;
  reg [7:0] rx_bytes [0:63];

  post_synth_top dut(
    .clk(clk), .rst(rst), .halted(halted), .gpio_in(gpio_in),
    .gpio_out(gpio_out), .uart_tx(uart_tx), .dbg_pc(dbg_pc),
    .dbg_flags(dbg_flags), .dbg_regs(dbg_regs), .dbg_ram(dbg_ram));

  always #(CLK_PERIOD/2) clk = ~clk;

  // Independent time-based 8N1 receiver (start, 8 data LSB first, stop).
  initial begin
    rx_count = 0;
    rx_errors = 0;
    forever begin
      @(negedge uart_tx);
      #(BIT_TIME/2);
      if (uart_tx !== 1'b0) begin
        rx_errors = rx_errors + 1;
      end else begin
        #(BIT_TIME);
        for (rxi = 0; rxi < 8; rxi = rxi + 1) begin
          rx_byte[rxi] = uart_tx;
          if (rxi < 7) #(BIT_TIME);
        end
        #(BIT_TIME);
        if (uart_tx !== 1'b1) begin
          rx_errors = rx_errors + 1;
        end else if (rx_count < 64) begin
          rx_bytes[rx_count] = rx_byte;
          rx_count = rx_count + 1;
        end else begin
          rx_errors = rx_errors + 1;
        end
      end
    end
  end

  initial begin
    rst = 1;
    repeat (2) @(posedge clk);
    @(negedge clk);
    rst = 0;
    #1;
    cycles = 0;
    while (!halted && cycles < MAX_CYCLES) begin
      @(posedge clk);
      cycles = cycles + 1;
      #1;
    end
    if (halted !== 1'b1) begin
      $display("POST_TIMEOUT cycles=%0d", cycles);
      $finish;
    end
    #(2 * BIT_TIME);
    $display("POST_STATE PC=%02X FLAGS=%X CYCLES=%0d",
             dbg_pc, dbg_flags, cycles);
    for (i = 0; i < 8; i = i + 1)
      $display("POST_REG %0d %02X", i, dbg_regs[63 - 8*i -: 8]);
    for (i = 0; i < 256; i = i + 1)
      $display("POST_RAM %0d %02X", i, dbg_ram[2047 - 8*i -: 8]);
    for (i = 0; i < rx_count; i = i + 1)
      $display("POST_UART_BYTE %0d %02X", i, rx_bytes[i]);
    $display("POST_UART COUNT=%0d ERRORS=%0d", rx_count, rx_errors);
    $finish;
  end
endmodule
"""


def write_program_package(outdir, prog):
    src = f"""library ieee;
use ieee.std_logic_1164.all;
use work.minicpu_pkg.all;

package fpga_program is
  constant PROGRAM : rom_t := work.{prog}_rom.PROG;
  constant RAM_INIT : ram_init_t := work.{prog}_ram.INIT;
end package fpga_program;
"""
    (outdir / "fpga_program.vhd").write_text(src)


def run_cmd(cmd, cwd, log_path):
    r = subprocess.run(cmd, cwd=cwd, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, text=True)
    log_path.write_text(r.stdout)
    if r.returncode != 0:
        print(r.stdout[-6000:])
        raise SystemExit(f"post_synth: command failed: {' '.join(cmd)}")
    return r.stdout


def hex_bytes(bs):
    return "".join(f"{b:02X}" for b in bs)


def expected_state(cpu):
    s = cpu.state()
    f = s["flags"]
    return {
        "pc": s["pc"],
        "flags": (f["z"] << 3) | (f["n"] << 2) | (f["c"] << 1) | f["v"],
        "regs": hex_bytes(s["regs"]),
        "ram": hex_bytes(s["ram"]),
        "cycles": s["cycles"],
        "uart": hex_bytes(s["uart_out"]),
        "uart_errors": 0,
    }


def parse_log(text):
    state = {}
    regs = {}
    ram = {}
    uart = []
    uart_meta = {}
    for line in text.splitlines():
        m = re.search(r"POST_STATE\s+PC=([0-9A-Fa-f]+)\s+FLAGS=([0-9A-Fa-f]+)"
                      r"\s+CYCLES=(\d+)", line)
        if m:
            state["pc"] = int(m.group(1), 16)
            state["flags"] = int(m.group(2), 16)
            state["cycles"] = int(m.group(3))
            continue
        m = re.search(r"POST_REG\s+(\d+)\s+([0-9A-Fa-f]{2})", line)
        if m:
            regs[int(m.group(1))] = int(m.group(2), 16)
            continue
        m = re.search(r"POST_RAM\s+(\d+)\s+([0-9A-Fa-f]{2})", line)
        if m:
            ram[int(m.group(1))] = int(m.group(2), 16)
            continue
        m = re.search(r"POST_UART_BYTE\s+(\d+)\s+([0-9A-Fa-f]{2})", line)
        if m:
            uart.append(int(m.group(2), 16))
            continue
        m = re.search(r"POST_UART\s+COUNT=(\d+)\s+ERRORS=(\d+)", line)
        if m:
            uart_meta["count"] = int(m.group(1))
            uart_meta["errors"] = int(m.group(2))
    if len(regs) == 8:
        state["regs"] = hex_bytes([regs[i] for i in range(8)])
    if len(ram) == 256:
        state["ram"] = hex_bytes([ram[i] for i in range(256)])
    if "count" in uart_meta:
        state["uart_errors"] = uart_meta["errors"]
        state["uart"] = hex_bytes(uart)
    return state


def compare(exp, got):
    diffs = []
    for key in ("pc", "flags", "regs", "ram", "cycles", "uart", "uart_errors"):
        if key not in got:
            diffs.append(f"{key}: missing from netlist dump")
        elif exp[key] != got[key]:
            if key == "ram":
                bad = [i for i in range(256)
                       if exp["ram"][2*i:2*i+2] != got["ram"][2*i:2*i+2]]
                diffs.append(f"ram: {len(bad)} bytes differ, first 0x{bad[0]:02X} "
                             f"(exp {exp['ram'][2*bad[0]:2*bad[0]+2]}, "
                             f"got {got['ram'][2*bad[0]:2*bad[0]+2]})")
            else:
                diffs.append(f"{key}: expected {exp[key]!r}, got {got[key]!r}")
    return diffs


def main():
    ap = argparse.ArgumentParser(description="MiniCPU-8 post-synthesis tests")
    ap.add_argument("--programs", default="sum1to10,array_sum,call_ret,hello")
    ap.add_argument("--dir", default="build/post_synth")
    ap.add_argument("--yosys", default=os.environ.get("YOSYS", "yosys"))
    ap.add_argument("--plugin", default=os.environ.get("GHDL_PLUGIN", "ghdl"))
    ap.add_argument("--iverilog", default=os.environ.get("IVERILOG", "iverilog"))
    args = ap.parse_args()

    outroot = (ROOT / args.dir).resolve()
    if outroot.exists():
        shutil.rmtree(outroot)
    outroot.mkdir(parents=True)

    datdir = subprocess.check_output(["yosys-config", "--datdir"],
                                     text=True).strip()
    cells_sim = Path(datdir) / "ice40" / "cells_sim.v"
    if not cells_sim.exists():
        raise SystemExit(f"post_synth: cells_sim.v not found at {cells_sim}")

    programs = [p.strip() for p in args.programs.split(",") if p.strip()]
    failures = []
    summary = {}

    for prog in programs:
        print(f"=== post-synth {prog} ===")
        outdir = outroot / prog
        outdir.mkdir()
        asm_path = ROOT / "programs" / f"{prog}.asm"
        text = asm_path.read_text()
        result = assembler.assemble_with_data(text)
        rom_src, _ = assembler.to_vhdl(result, str(asm_path), result.ram)
        (outdir / f"{prog}_rom.vhd").write_text(rom_src)
        write_program_package(outdir, prog)

        cpu = isa_sim.MiniCPU8(result.words, result.ram, max_cycles=MAX_CYCLES,
                               gpio_in=0, clks_per_bit=CLKS_PER_BIT).run()
        if not cpu.halted or cpu.timeout:
            raise SystemExit(f"post_synth: golden {prog} did not halt")
        exp = expected_state(cpu)

        sources = [str(ROOT / s) for s in SOURCES]
        sources = sources[:-1] + [
            str(outdir / f"{prog}_rom.vhd"),
            str(outdir / "fpga_program.vhd"),
            str(ROOT / "post_synth_top.vhd"),
        ]
        netlist = outdir / "post_synth_top.v"
        yosys_log = outdir / "yosys.log"
        script = (
            "ghdl --std=08 " + " ".join(sources) +
            " -e post_synth_top; synth_ice40 -top post_synth_top; "
            f"write_verilog -noattr {netlist}"
        )
        run_cmd([args.yosys, "-m", args.plugin, "-p", script],
                ROOT, yosys_log)

        tb = outdir / "post_tb.v"
        tb.write_text(TB_TEMPLATE.replace("__CPB__", str(CLKS_PER_BIT))
                      .replace("__MAX_CYCLES__", str(MAX_CYCLES)))
        sim = outdir / "sim.vvp"
        run_cmd([args.iverilog, "-g2012", "-o", str(sim), str(netlist),
                 str(tb), str(cells_sim)], outdir, outdir / "iverilog.log")
        log = run_cmd(["vvp", str(sim)], outdir, outdir / "sim.log")
        got = parse_log(log)
        diffs = compare(exp, got)
        summary[prog] = {
            "cycles": exp["cycles"],
            "uart": exp["uart"],
            "passed": not diffs,
        }
        if diffs:
            failures.append((prog, diffs, exp, got))
            print(f"  FAIL ({len(diffs)} differences)")
        else:
            print(f"  PASS: cycles={exp['cycles']} "
                  f"uart={exp['uart'] or '(none)'}")

    (outroot / "summary.json").write_text(json.dumps(summary, indent=1))
    if failures:
        print("=" * 70)
        print(f"POST-SYNTHESIS: {len(failures)} of {len(programs)} FAILED")
        for prog, diffs, exp, got in failures:
            print(f"\n--- {prog} ---")
            print("expected:", json.dumps(exp))
            print("actual:  ", json.dumps(got))
            for d in diffs:
                print("  DIFF", d)
        raise SystemExit(1)
    print(f"POST-SYNTHESIS: {len(programs)} programs, 0 mismatches")


if __name__ == "__main__":
    main()
